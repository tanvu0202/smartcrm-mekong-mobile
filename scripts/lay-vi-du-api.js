const md = [];
let tokenMask = [];
const mask = (s) => tokenMask.reduce((t, k) => t.split(k).join('<token>'), s).replace(/"token": "[^"]+"/g, '"token": "<token>"'); // che cả token vừa nhận ở chính lần đăng nhập

/** Rút gọn mảng dài (giữ 2 phần tử đầu) để file ví dụ gọn; ghi chú rõ đã rút gọn. */
function shorten(v) {
  if (Array.isArray(v)) return v.length > 2 ? [...v.slice(0, 2).map(shorten), `… (${v.length - 2} more items)`] : v.map(shorten);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, shorten(x)]));
  return v;
}

async function call(title, method, url, { token, body } = {}) {
  const headers = {};
  if (token) headers.Authorization = `Bearer ${token}`;
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  const res = await fetch(BASE + url, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const text = await res.text();
  let json = null; try { json = text ? JSON.parse(text) : null; } catch { /* không phải JSON */ }
  md.push(`### ${title}`, '', '```http', `${method} ${url.startsWith('/') ? '/api' + url : url}${token ? '\nAuthorization: Bearer <token>' : ''}${body !== undefined ? '\nContent-Type: application/json\n\n' + JSON.stringify(body, null, 2) : ''}`, '```', '',
    '```http', `HTTP ${res.status}${json !== null ? '\n\n' + mask(JSON.stringify(shorten(json), null, 2)) : ''}`, '```', '');
  console.log(`${String(res.status).padEnd(4)} ${method.padEnd(6)} ${url}   ${title}`);
  return { status: res.status, json };
}

